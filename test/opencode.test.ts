import { test, before } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { DatabaseSync } from "node:sqlite";
// Point the gateway at a throwaway database before any storage module is loaded.
const dir = mkdtempSync(join(tmpdir(), "gateway-opencode-"));
process.env.VIEWTOWER_GATEWAY_DIR = dir;
let settings: typeof import("../src/integrations/opencode/settings");
let toToolCall: typeof import("../src/integrations/opencode/hook-input").toToolCall;
before(async () => {
  settings = await import("../src/integrations/opencode/settings");
  ({ toToolCall } = await import("../src/integrations/opencode/hook-input"));
});
const base = {
  session_id: "session",
  cwd: dir,
  tool_use_id: "call",
  tool_name: "bash",
  tool_input: { command: "git status" },
  hook_event_name: "PreToolUse",
};
function hook(phase: string, input: unknown, mode = "enforce") {
  const r = spawnSync(
    process.execPath,
    ["--import", "tsx", join(__dirname, "../src/main.ts"), "hook", phase, "--agent", "opencode"],
    {
      input: JSON.stringify(input),
      encoding: "utf8",
      env: { ...process.env, VIEWTOWER_GATEWAY_DIR: dir, VIEWTOWER_GATEWAY_MODE: mode },
    }
  );
  assert.equal(r.status, 0, r.stderr);
  return JSON.parse(r.stdout);
}
test("opencode tools map to the names the services understand", () => {
  const edit = toToolCall({ ...base, tool_name: "edit", tool_input: { filePath: "a.ts", oldString: "a", newString: "b" } });
  assert.equal(edit.toolName, "Edit");
  assert.deepEqual(edit.toolInput, { file_path: "a.ts", old_string: "a", new_string: "b", replace_all: undefined });
  assert.equal(edit.toolUseId, "opencode:session:call");
  assert.equal(edit.integration, "opencode");
  const read = toToolCall({ ...base, tool_name: "read", tool_input: { filePath: "a.ts" } });
  assert.equal(read.toolName, "Read");
  assert.equal((read.toolInput as { file_path: string }).file_path, "a.ts");
  const patch = toToolCall({
    ...base,
    tool_name: "apply_patch",
    tool_input: { patchText: "*** Begin Patch\n*** Add File: a.ts\n+hello\n*** End Patch" },
  });
  assert.equal(patch.toolName, "MultiEdit");
  assert.deepEqual((patch.toolInput as { file_paths: string[] }).file_paths, ["a.ts"]);
  const v2Edit = toToolCall({ ...base, tool_name: "edit", tool_input: { path: "b.ts", oldString: "a", newString: "b" } });
  assert.equal((v2Edit.toolInput as { file_path: string }).file_path, "b.ts");
  assert.equal(toToolCall({ ...base, tool_name: "shell" }).toolName, "Bash");
  const v2Patch = toToolCall({
    ...base,
    tool_name: "patch",
    tool_input: { patchText: "*** Begin Patch\n*** Add File: c.ts\n+hi\n*** End Patch" },
  });
  assert.deepEqual((v2Patch.toolInput as { file_paths: string[] }).file_paths, ["c.ts"]);
  const other = toToolCall({ ...base, tool_name: "todowrite", tool_input: { todos: [] } });
  assert.equal(other.toolName, "todowrite");
  assert.deepEqual(other.toolInput, { todos: [] });
  assert.deepEqual(toToolCall({ ...base, tool_name: "list", tool_input: { path: "src" } }).toolName, "Glob");
  assert.equal(toToolCall({ ...base, tool_name: "question", tool_input: { questions: [] } }).toolName, "AskUserQuestion");
  assert.throws(() => toToolCall({ ...base, session_id: "" }), /Incomplete opencode hook payload/);
  assert.throws(() => toToolCall({ ...base, tool_name: "" }), /Incomplete opencode hook payload/);
});
test("opencode setup writes the plugin, can be repeated and uninstalled", () => {
  const { hooksInstalled, installHooks, uninstallHooks } = settings;
  const path = join(dir, "plugins", "viewtower.js");
  assert.equal(installHooks({ path, installed: true }).replaced, 0);
  const source = readFileSync(path, "utf8");
  assert.match(source, /^\/\/ viewtower opencode plugin\. Generated by "viewtower init --agent opencode"/);
  assert.match(source, /hook pre --agent opencode/);
  assert.match(source, /windowsHide: true/);
  assert.equal(installHooks({ path, installed: true }).replaced, 1);
  assert.equal(hooksInstalled(path), true);
  assert.equal(uninstallHooks({ path }).removed, 1);
  assert.equal(existsSync(path), false);
  assert.equal(hooksInstalled(path), false);
  const config = join(dir, "opencode.json");
  writeFileSync(config, "{}");
  assert.throws(() => installHooks({ path: config, installed: true }), /is not a viewtower plugin/);
  assert.equal(readFileSync(config, "utf8"), "{}");
});
test("generated opencode plugin is a valid opencode 2.x plugin definition", async () => {
  const path = join(dir, "check", "viewtower.mjs");
  settings.installHooks({ path, installed: true });
  const mod = await import(pathToFileURL(path).href);
  assert.equal(mod.default.id, "viewtower");
  assert.equal(typeof mod.default.setup, "function");
});
// Loads the generated plugin with stub hook commands and a fake opencode context; returns the registered hooks.
async function loadPlugin(name: string, pre: string) {
  const work = join(dir, name);
  mkdirSync(work, { recursive: true });
  const script = (file: string, code: string) => {
    writeFileSync(join(work, file), code);
    return `"${process.execPath}" "${join(work, file)}"`;
  };
  const log = join(work, "post.log");
  const commands = {
    pre: script("pre.cjs", `process.stdout.write(${JSON.stringify(pre)})`),
    post: script(
      "post.cjs",
      `let d="";process.stdin.on("data",c=>d+=c).on("end",()=>{require("fs").appendFileSync(${JSON.stringify(log)},d+"\\n");process.stdout.write('{"hookSpecificOutput":{"updatedToolOutput":"short"}}')})`
    ),
    prompt: script("noop.cjs", ""),
    session: script("noop.cjs", ""),
  };
  const path = join(work, "viewtower.mjs");
  settings.installHooks({ path, installed: true });
  writeFileSync(
    path,
    readFileSync(path, "utf8").replace(/const COMMANDS = [\s\S]*?\n\};/, `const COMMANDS = ${JSON.stringify(commands)};`)
  );
  const hooks: Record<string, (input: any) => Promise<void> | void> = {};
  const register = (domain: string) => async (name: string, fn: (input: any) => Promise<void> | void) => {
    hooks[`${domain}.${name}`] = fn;
    return { dispose: async () => {} };
  };
  const ctx = { location: { directory: work }, tool: { hook: register("tool") }, session: { hook: register("session") } };
  await (await import(pathToFileURL(path).href)).default.setup(ctx);
  const posts = () =>
    existsSync(log)
      ? readFileSync(log, "utf8")
          .trim()
          .split("\n")
          .map((l) => JSON.parse(l))
      : [];
  return { hooks, posts };
}
test("generated opencode plugin blocks denied calls and never records them", async () => {
  const { hooks, posts } = await loadPlugin(
    "deny",
    '{"hookSpecificOutput":{"permissionDecision":"deny","permissionDecisionReason":"no"}}'
  );
  await assert.rejects(
    Promise.resolve(hooks["tool.execute.before"]({ tool: "shell", sessionID: "s", id: "c", input: { command: "x" } })),
    /no/
  );
  assert.deepEqual(posts(), []);
});
test("generated opencode plugin records results and replaces text output", async () => {
  const { hooks, posts } = await loadPlugin("allow", "{}");
  const call: any = { tool: "shell", sessionID: "s", id: "c", input: { command: "ls" } };
  await hooks["session.context"]({ sessionID: "s", model: { id: "gpt-x" } });
  await hooks["tool.execute.before"](call);
  call.status = "completed";
  call.result = { output: { exit: 0 }, content: [{ type: "text", text: "long output" }] };
  await hooks["tool.execute.after"](call);
  assert.deepEqual(call.result.content, [{ type: "text", text: "short" }]);
  const failed: any = {
    tool: "read",
    sessionID: "s",
    id: "f",
    input: { path: "x" },
    status: "error",
    error: new Error("missing"),
  };
  await hooks["tool.execute.after"](failed);
  const [ok, fail] = posts();
  assert.equal(ok.hook_event_name, "PostToolUse");
  assert.equal(ok.tool_response, "long output");
  assert.equal(ok.model, "gpt-x");
  assert.equal(fail.hook_event_name, "PostToolUseFailure");
  assert.equal(fail.error, "missing");
});
test("opencode uses shared enforcement", () => {
  assert.equal(hook("pre", { ...base, tool_input: { command: "rm -rf x" } }).hookSpecificOutput.permissionDecision, "deny");
  assert.deepEqual(hook("pre", { ...base, tool_use_id: "allowed" }), {});
});
test("opencode prompt and post are recorded with prompt and integration", () => {
  assert.deepEqual(
    hook("prompt", { session_id: "session", cwd: dir, prompt_id: "msg", prompt: "hi", hook_event_name: "UserPromptSubmit" }),
    {}
  );
  hook("post", { ...base, hook_event_name: "PostToolUse", tool_response: "On branch main\n" });
  const db = new DatabaseSync(join(dir, "gateway.sqlite"));
  const row = db.prepare("SELECT * FROM tool_calls WHERE tool_use_id = ?").get("opencode:session:call")!;
  assert.equal(row.integration, "opencode");
  assert.equal(row.prompt_id, "opencode:session:msg");
  db.close();
});
