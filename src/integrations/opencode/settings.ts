import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import * as shared from "../shared/settings";

// opencode has no command hooks: it loads JS plugins. The generated plugin runs the same hook commands.

const MARKER = '// viewtower opencode plugin. Generated by "viewtower init --agent opencode"; rerun init instead of editing.';

export function defaultSettingsPath(): string {
  return join(process.env.XDG_CONFIG_HOME || join(homedir(), ".config"), "opencode", "plugins", "viewtower.js");
}
export function installHooks(options: { path?: string } & shared.HookCommandOptions = {}): shared.InstallResult {
  const path = options.path ?? defaultSettingsPath();
  const commands = {
    pre: shared.hookCommand("pre", { ...options, integration: "opencode" }),
    post: shared.hookCommand("post", { ...options, integration: "opencode" }),
    prompt: shared.hookCommand("prompt", { ...options, integration: "opencode" }),
    session: shared.hookCommand("session", { ...options, integration: "opencode" }),
  };
  const replaced = existsSync(path) ? 1 : 0;
  if (replaced && !hooksInstalled(path)) throw new Error(`${path} exists and is not a viewtower plugin; nothing was changed.`);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, pluginSource(commands));
  return { path, backup: null, replaced, commands: Object.values(commands) };
}
export function uninstallHooks(options: { path?: string } = {}) {
  const path = options.path ?? defaultSettingsPath();
  let removed = 0;
  if (hooksInstalled(path)) {
    rmSync(path);
    removed = 1;
  }
  return { path, backup: null, removed };
}
export function hooksInstalled(path?: string) {
  try {
    return readFileSync(path ?? defaultSettingsPath(), "utf8").includes(MARKER);
  } catch {
    return false;
  }
}
function pluginSource(commands: Record<string, string>): string {
  return `${MARKER}
import { spawn } from "node:child_process";

const COMMANDS = ${JSON.stringify(commands, null, 2)};

function run(phase, payload) {
  return new Promise((resolve) => {
    let out = "";
    let child;
    try {
      child = spawn(COMMANDS[phase], { shell: true, stdio: ["pipe", "pipe", "ignore"] });
    } catch {
      return resolve({});
    }
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (d) => (out += d));
    child.on("error", () => resolve({}));
    child.on("close", () => {
      try {
        resolve(JSON.parse(out).hookSpecificOutput ?? {});
      } catch {
        resolve({});
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify(payload));
  });
}

// What the model sees of a result: its content parts, or the stringified output when there are none.
function visible(result) {
  const content = result?.content;
  if (typeof content === "string") return content;
  if (Array.isArray(content) && content.length) return content.map((p) => (p.type === "text" ? p.text : \`[\${p.type}]\`)).join("\\n");
  const output = result?.output;
  return typeof output === "string" ? output : JSON.stringify(output ?? "");
}
const textOnly = (result) => !Array.isArray(result?.content) || result.content.every((p) => p.type === "text");

// opencode 2.x plugin: a default definition with an id and a setup function.
export default {
  id: "viewtower",
  async setup(ctx) {
    const cwd = ctx.location?.directory ?? process.cwd();
    const models = new Map();
    const started = new Map();
    const base = (sessionID) => ({ session_id: sessionID, cwd, model: models.get(sessionID) });
    // Once per opencode start (also on resume, not per subagent session): company sync and dashboard. Not awaited: startup stays fast.
    run("session", { cwd, hook_event_name: "SessionStart", source: "startup" });
    await ctx.session.hook("context", (c) => {
      if (c.sessionID && c.model?.id) models.set(c.sessionID, c.model.id);
    });
    await ctx.session.hook("prompt", async (p) => {
      await run("prompt", {
        ...base(p.sessionID),
        hook_event_name: "UserPromptSubmit",
        prompt_id: p.messageID ?? String(Date.now()),
        prompt: p.prompt?.text ?? "",
      });
    });
    await ctx.session.hook("compaction", async (c) => {
      if (c.sessionID) await run("session", { session_id: c.sessionID, hook_event_name: "PreCompact" });
    });
    await ctx.tool.hook("execute.before", async (call) => {
      const reply = await run("pre", {
        ...base(call.sessionID),
        hook_event_name: "PreToolUse",
        tool_name: call.tool,
        tool_use_id: call.id,
        tool_input: call.input,
      });
      // Throwing fails the call; opencode gives the message to the model.
      if (reply.permissionDecision === "deny") throw new Error(reply.permissionDecisionReason || "Blocked by viewtower");
      started.set(call.id, Date.now());
    });
    // Runs only for calls that ran (a denied call never gets here), completed or failed.
    await ctx.tool.hook("execute.after", async (call) => {
      const start = started.get(call.id);
      started.delete(call.id);
      const failed = call.status === "error";
      const reply = await run("post", {
        ...base(call.sessionID),
        hook_event_name: failed ? "PostToolUseFailure" : "PostToolUse",
        tool_name: call.tool,
        tool_use_id: call.id,
        tool_input: call.input,
        ...(failed ? { error: call.error?.message ?? String(call.error) } : { tool_response: visible(call.result) }),
        duration_ms: start ? Date.now() - start : undefined,
      });
      // Shortened result: only text results are replaced, so images etc. are never dropped.
      if (!failed && typeof reply.updatedToolOutput === "string" && textOnly(call.result))
        call.result = { ...call.result, content: [{ type: "text", text: reply.updatedToolOutput }] };
    });
  },
};
`;
}
